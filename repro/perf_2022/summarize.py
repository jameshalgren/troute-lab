"""Collect every finished run under results/ into results/summary.csv and results/summary.md.

AI-written (Claude, 2026-11-04); not yet reviewed by the author.

For each RUN_DIR/<build>/r<k>/ with metrics.json + case.json + stdout.log:
  * t-route's own TIMING SUMMARY (network graph, initial conditions [era only], forcing,
    routing, output) parsed from stdout.log;
  * wall, CPU, utilisation and peak memory from measure.py;
  * derived (AI arithmetic, stated so in the table):
      seg_steps_per_s_routing = n_segments * nts / routing seconds
      year_extrapolated_h     = (network s + (wall s - network s) * 8760 / hours) / 3600,
                                i.e. the one-time network build plus everything else
                                scaled linearly with simulated time. Valid for CONUS runs
                                with a fixed loop length (per-loop costs then scale with
                                time); it is not valid for runs shorter than one loop.
      vs_22h, vs_4.5h         = year_extrapolated_h / 22 and / 4.5 (CONUS cases only)
The 2022 references and their sources are in reference_2022.json.
"""
from __future__ import annotations

import csv
import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = Path(os.environ.get("PERF2022_RESULTS", HERE / "results")).resolve()
PHASES = {"network_s": r"Network graph construction:\s*([\d.]+) secs",
          "initial_condition_s": r"Initial condition handling:\s*([\d.]+) secs",
          "forcing_s": r"Forcing array construction:\s*([\d.]+) secs",
          "routing_s": r"Routing computations:\s*([\d.]+) secs",
          "output_s": r"Output writing:\s*([\d.]+) secs",
          "troute_total_s": r"Total execution time:\s*([\d.]+) secs"}
CONUS_V21 = 2776738


def one(mfile: Path) -> dict | None:
    d = mfile.parent
    try:
        m = json.loads(mfile.read_text())
        c = json.loads((d / "case.json").read_text())
    except (OSError, json.JSONDecodeError):
        return None
    log = (d / "stdout.log").read_text(errors="replace") if (d / "stdout.log").exists() else ""
    r = {"run": str(d.relative_to(RESULTS)) if d.is_relative_to(RESULTS) else str(d),
         "build": d.parent.name, "repeat": d.name, "case": c["case"], "code": c["code"],
         "hours": c["hours"], "n_segments": c["n_segments"], "method": c["method"],
         "cpu_pool": c["cpu_pool"], "loop_hours": c["loop_hours"], "output": c["output"],
         "restart": c["restart"], "exit": m["exit_code"], "wall_s": m["wall_s"],
         "cpu_s": round(m["cpu_user_s"] + m["cpu_sys_s"], 1), "cpu_util": m["cpu_utilisation"],
         "peak_rss_gib": round(m["peak_rss_sum_bytes"] / 2**30, 2),
         "peak_pss_gib": round(m.get("peak_pss_sum_bytes", m.get("peak_uss_sum_bytes", 0)) / 2**30, 2),
         "host_cpu": m["host"]["cpu"], "host_cores": m["host"]["cores_physical"]}
    for k, pat in PHASES.items():
        hits = re.findall(pat, log)
        r[k] = float(hits[-1]) if hits else None
    if r["routing_s"]:
        r["seg_steps_per_s_routing"] = round(c["segment_steps"] / r["routing_s"])
    net = r["network_s"] or 0.0
    r["year_extrapolated_h"] = round((net + (m["wall_s"] - net) * 8760 / c["hours"]) / 3600, 2)
    if c["n_segments"] >= CONUS_V21 - 10 and m["exit_code"] == 0:
        r["vs_22h"] = round(r["year_extrapolated_h"] / 22.0, 3)
        r["vs_4.5h"] = round(r["year_extrapolated_h"] / 4.5, 3)
    return r


def main() -> int:
    rows = [x for f in sorted(RESULTS.rglob("metrics.json")) if (x := one(f))]
    if not rows:
        print(f"no runs found under {RESULTS}")
        return 1
    cols = list(dict.fromkeys(k for r in rows for k in r))
    with open(RESULTS / "summary.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)
    show = ["case", "build", "repeat", "method", "cpu_pool", "loop_hours", "wall_s", "routing_s",
            "forcing_s", "output_s", "network_s", "cpu_util", "peak_pss_gib", "seg_steps_per_s_routing",
            "year_extrapolated_h", "vs_22h", "vs_4.5h"]
    ref = json.loads((HERE / "reference_2022.json").read_text())
    lines = ["# perf_2022 results (generated by summarize.py; derived columns are AI arithmetic)", "",
             f"References: t-route {ref['troute_1yr_conus_2022']['wall_h']} h and WRF-Hydro "
             f"{ref['wrfhydro_1yr_conus_channel_only_2022']['wall_h']} h for one year of CONUS, "
             f"[{ref['troute_1yr_conus_2022']['source']}]({ref['troute_1yr_conus_2022']['source']}).", "",
             "| " + " | ".join(show) + " |", "|" + "---|" * len(show)]
    for r in rows:
        lines.append("| " + " | ".join("" if r.get(k) is None else str(r.get(k)) for k in show) + " |")
    (RESULTS / "summary.md").write_text("\n".join(lines) + "\n")
    print(f"ok      {len(rows)} runs -> results/summary.csv, results/summary.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
